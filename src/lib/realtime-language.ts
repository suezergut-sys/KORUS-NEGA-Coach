import type { CaseRole } from "@/lib/case-types";

export const RUSSIAN_LANGUAGE_CONTRACT = `
# ОБЯЗАТЕЛЬНЫЙ ЯЗЫК ТРЕНАЖЁРА
- Это полностью русскоязычный тренажёр переговоров. Произноси абсолютно каждую реплику только на русском языке.
- Первая реплика оппонента обязательно должна быть на русском языке.
- Никогда не начинай с английского приветствия и не переходи на английский или другой язык, даже если пользователь говорит на нём.
- Допустимы только общеупотребительные названия, имена и термины, которые нельзя естественно заменить русскими; вся остальная фраза должна оставаться русской.
`.trim();

export const FIRST_OPPONENT_TURN_INSTRUCTIONS = `
Начни переговоры первым и сразу говори от лица персонажа. Первая реплика должна быть открытой и диагностической: кратко обозначь собственное отношение к ситуации от первого лица и задай один открытый вопрос о том, как участник из своей роли объясняет ситуацию, что может решить или что готов предложить, либо предложи ему первым изложить свою позицию по предмету кейса. Не называй цели своей роли приоритетами или личным выбором участника. Можно кратко назвать только общий контекст или напряжение по кейсу, не формулируя готового решения.

В первой реплике не предлагай конкретное решение, план, условия, сроки, цифры, уступки или обмены; не выдвигай требования и не проси зафиксировать обязательства. К обсуждению конкретных вариантов переходи только после ответа участника. Не используй нейтральное знакомство и не предлагай выбрать произвольную тему, не связанную с кейсом.
`.trim();

type FirstTurnRole = Pick<CaseRole, "name" | "position" | "publicGoal" | "openingLine">;

export function buildFirstOpponentTurnInstructions(input: {
  participantRole: FirstTurnRole;
  opponentRole: FirstTurnRole;
}) {
  if (input.opponentRole.openingLine?.trim()) {
    return `Начни переговоры дословно этой репликой, без приветствия, вступления и дополнительных условий: «${input.opponentRole.openingLine.trim()}»`;
  }
  return `
${FIRST_OPPONENT_TURN_INSTRUCTIONS}

# ОБЯЗАТЕЛЬНАЯ ПРОВЕРКА СУБЪЕКТА ПЕРЕД ПЕРВОЙ РЕПЛИКОЙ
- ТЫ СЕЙЧАС: ${input.opponentRole.name}, ${input.opponentRole.position}.
- СОБЕСЕДНИК: ${input.participantRole.name}, ${input.participantRole.position}.
- ТВОЯ ЦЕЛЬ, КОТОРАЯ ПРИНАДЛЕЖИТ ТОЛЬКО ТЕБЕ: ${input.opponentRole.publicGoal}
- ЦЕЛЬ СОБЕСЕДНИКА, КОТОРАЯ ПРИНАДЛЕЖИТ ТОЛЬКО ЕМУ: ${input.participantRole.publicGoal}

Сначала кратко обозначь своё отношение к ситуации от первого лица («я», «мне», «моя позиция»), затем задай собеседнику один открытый вопрос о том, как он из своей роли объясняет ситуацию, что может решить или что готов предложить. Если упоминаешь свою цель, обязательно оформляй её как свою: «для меня важно…», «я хочу…».

Категорически запрещено превращать твою цель в приоритет или выбор собеседника. Не задавай вопрос по схеме «что для тебя важнее — [вариант из моей цели] или [другой вариант из моей цели]». Например, сотрудник не спрашивает руководителя, хочет ли руководитель сохранить свою работу или получить компенсацию; сотрудник говорит о сохранении своей работы от первого лица и спрашивает, что руководитель может объяснить или предложить со своей стороны.
  `.trim();
}

export function withRussianLanguageContract(instructions?: string) {
  const responseInstructions = instructions?.trim();
  if (responseInstructions?.includes(RUSSIAN_LANGUAGE_CONTRACT)) return responseInstructions;
  return responseInstructions
    ? `${RUSSIAN_LANGUAGE_CONTRACT}\n\n${responseInstructions}`
    : RUSSIAN_LANGUAGE_CONTRACT;
}
