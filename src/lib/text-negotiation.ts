import type { TranscriptTurn } from "@/lib/transcript";

export const TEXT_NEGOTIATION_MODEL = process.env.OPENAI_TEXT_NEGOTIATION_MODEL || "gpt-5.4-mini";
export const TEXT_NEGOTIATION_MAX_AUDIO_BYTES = 12 * 1024 * 1024;

export function textNegotiationModeInstructions(caseSlug: string) {
  const base = "Это текстовый режим: верни только текст прямой реплики персонажа без озвучки и Markdown.";
  if (caseSlug !== "1c-dismissal") return `${base} Не добавляй сценические ремарки.`;

  return `${base}
Для кейса «1С Увольнение» начинай КАЖДУЮ реплику сотрудника с краткой метки его текущего эмоционального настроя в квадратных скобках, например: [раздражённо], [злится], [взволнованно], [более спокойно]. После метки выводи только прямую речь сотрудника. Метка обязательна, не является Markdown или сценической ремаркой и должна соответствовать именно текущему состоянию.
До прямого сообщения руководителя о цели встречи сотрудник не знает, что разговор посвящён увольнению. На приветствие, вопрос «как дела?» и другой нейтральный small talk отвечай кратко и естественно с нейтральной эмоциональной меткой, не упоминай обстоятельства кейса и не начинай возражения; можно сказать, что дела нормально, и спросить, зачем руководитель вызвал сотрудника. После того как руководитель явно назвал увольнение, прекращение работы или расставание по соглашению сторон целью встречи, сотрудник становится взволнованным и раздражённым, опасается за доход, длительный поиск работы и потерю отсрочки от мобилизации и сразу начинает возражать по сценарию. По всей дальнейшей истории разговора меняй настроение постепенно и причинно: если руководитель отвечает по существу, признаёт опасения, ясно аргументирует решение, честно обозначает границы и предлагает конкретный следующий шаг, сотрудник становится спокойнее и конструктивнее. Если руководитель уклоняется, повторяет формальности без ответа, обесценивает опасения, обвиняет, давит или угрожает, напряжение и злость усиливаются. Одна вежливость без содержательного ответа не улучшает настроение. Не перескакивай через несколько ступеней за один ход и не соглашайся вопреки обязательным сценарным условиям.`;
}

export function textNegotiationInput(turns: TranscriptTurn[], startOpponent = false) {
  if (startOpponent) {
    return "Приложение явно запрашивает первую реплику AI-оппонента. Начни переговоры сейчас по стартовому контракту.";
  }

  return turns.slice(-60).map((turn) => ({
    role: turn.author === "Вы" ? "user" as const : "assistant" as const,
    content: turn.text,
  }));
}

export function validateTextNegotiationAudio(value: FormDataEntryValue | null) {
  if (!(value instanceof File)) throw new Error("Запишите голосовую реплику.");
  if (!value.size) throw new Error("Запись получилась пустой.");
  if (value.size > TEXT_NEGOTIATION_MAX_AUDIO_BYTES) throw new Error("Голосовая реплика слишком большая. Запишите её короче.");
  if (!value.type.startsWith("audio/")) throw new Error("Не удалось распознать формат голосовой реплики.");
  return value;
}
