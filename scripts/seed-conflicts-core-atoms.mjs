const rows = candidates.map((atom) => {
  const chunk = chunks.find((item) => item.content.includes(atom.source_quote));
  if (!chunk) throw new Error(`Цитата не найдена в исходных фрагментах: ${atom.title}`);
  return {
    ...atom,
    source_id: source.id,
    chunk_id: chunk.id,
    methodology_version: "conflicts-v0-candidate",
    verification_status: "candidate",
  };
});

const { data, error } = await supabase
  .from("method_atoms")
  .upsert(rows, { onConflict: "source_id,kind,title,source_quote", ignoreDuplicates: true })
  .select("id,title");
if (error) throw error;
