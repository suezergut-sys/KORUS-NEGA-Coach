Манипулятивные техники во время увольнения.

Давление срочностью: руководитель говорит «Нужно подписать сегодня», «Потом условий уже не будет», «У нас нет времени это обсуждать». Решение принимается в спешке, без анализа условий, документов и последствий.
Ложная альтернатива: руководитель говорит «Либо по собственному, либо по статье», «Или подписываешь сейчас, или будет хуже». Искусственно сужается выбор. Стороны перестают искать рабочий вариант.
Угроза последствиями: руководитель говорит «Если не согласишься, будут проблемы с рекомендациями», «Это может повлиять на выплаты». Переговоры превращаются в конфликт и взаимное давление. Растут юридические и репутационные риски.
Вина и долг / вызывание чувства вины: руководитель говорит «Мы тебя учили, развивали, а ты теперь требуешь компенсацию», «После всего, что компания для тебя сделала…». Решение начинает приниматься из чувства вины, а не на основе фактов, процедур и реальных возможностей.
Обесценивание позиции другой стороны: руководитель говорит «Твои требования завышены», «Ты не на такой позиции, чтобы это обсуждать», «Ты не так много сделал». Возникает защита, обида и эскалация конфликта. Стороны перестают слышать аргументы.
Скрытая угроза / намёки: руководитель говорит «Подумай, как это потом будет выглядеть», «Такие вещи обычно запоминаются», «Лучше не усложнять». Создаётся тревога и давление, но без прямого обсуждения сути. Это мешает открытому разговору.
Псевдокомпромисс: руководитель говорит «Мы и так идём тебе навстречу — увольняем спокойно», «Считай, тебе повезло с такими условиями». Внешне выглядит как компромисс, но по сути одна сторона навязывает другой свои условия.
Перегрузка деталями: руководитель даёт много документов, сложных формулировок, ссылок на процедуры и просит быстро подписать. Важные условия могут потеряться в деталях. Стороны устают и принимают решения без ясности.
Подмена темы: вместо условий увольнения руководитель говорит о лояльности, благодарности, командности или личных качествах. Основные вопросы остаются нерешёнными. Разговор становится эмоциональным и бесконечным.
Газлайтинг: руководитель говорит «Я такого не говорил», «Ты неправильно понял», «Тебе показалось, что мы это обещали». Стороны начинают спорить о том, кто что говорил. Теряется доверие, растёт риск конфликта.
Игры с временем: руководитель затягивает ответы, переносит встречи, не даёт ясности по дате или выплатам. Время становится инструментом давления. Растёт неопределённость, страдают процессы и отношения.
Символическое давление статусом: руководитель говорит «Это уже решено на уровне директора», «Юристы сказали, что так правильно». Стороны реагируют на статус или авторитет, а не на реальные основания и документы.
Показная жёсткость / игра на страхе: холодный тон, демонстративное недовольство, фразы «С таким подходом будет сложно», «Я бы на твоём месте подумал». Страх и напряжение заменяют обсуждение условий. Стороны начинают защищаться, а не договариваться.
